"""Expert data of one training chunk: allocation, episode configurations, generation.

A stage's trajectories are split into chunks with equal counts per start region
(quadrants in 2D, octants in 3D) and the stage's perturbed share split proportionally.
Each chunk is generated by the Numba-compiled expert of the dimension, in a thread
pool sharing RAM: the kernels release the GIL, and every trajectory is its own task,
so rollouts of different lengths balance across the workers.

This module imports neither TensorFlow nor the compiled kernels until data is
generated, so the stage driver can plan chunks without them.
"""

from concurrent.futures import ThreadPoolExecutor
import math
import os
import time

import numpy as np

from modules.perturbations import DRIFT_MODE, NORMAL_MODE, allocate_mode_chunks, episode_perturbation
from modules.regions import region_bounds, region_count

# Offset between the seeds of a chunk's training episodes and of its validation episodes.
VALIDATION_SEED_OFFSET = 50_000_021


def compiled_expert(dimension):
    """The compiled expert of a dimension: fixed and online generators, and its warm-up."""
    if int(dimension) == 2:
        from training import compiled_expert_2d as expert
        warm_up = expert.warm_up_compiled_expert_2d
    else:
        from training import compiled_expert_3d as expert
        warm_up = expert.warm_up_compiled_expert_3d
    return expert.generate_fixed_trajectory, expert.generate_online_trajectory, warm_up


def proportional_chunk_allocations(total_counts, chunk_size):
    """Allocate proportional chunks while preserving exact region totals."""
    if chunk_size < 1:
        raise ValueError("chunk_size must be positive.")

    remaining = {int(region): int(count) for region, count in total_counts.items()}
    allocations = []
    while sum(remaining.values()) > 0:
        current_size = min(int(chunk_size), sum(remaining.values()))
        total_remaining = sum(remaining.values())
        exact = {
            region: current_size * count / total_remaining
            for region, count in remaining.items()
        }
        allocation = {
            region: min(remaining[region], math.floor(exact[region]))
            for region in remaining
        }
        unassigned = current_size - sum(allocation.values())
        while unassigned:
            candidates = [
                region
                for region in remaining
                if allocation[region] < remaining[region]
            ]
            chosen = max(
                candidates,
                key=lambda region: (
                    exact[region] - allocation[region],
                    remaining[region],
                ),
            )
            allocation[chosen] += 1
            unassigned -= 1
        allocation = {
            region: count for region, count in allocation.items() if count
        }
        allocations.append(allocation)
        for region, count in allocation.items():
            remaining[region] -= count
    return allocations


def balanced_region_counts(count, dimension):
    """``count`` trajectories split evenly over the regions, the first regions taking the remainder."""
    regions = region_count(dimension)
    base, remainder = divmod(int(count), regions)
    return {
        region: base + (1 if region < remainder else 0)
        for region in range(regions)
        if base + (1 if region < remainder else 0) > 0
    }


def chunk_plan(settings):
    """The (region counts, perturbation mode counts) of every chunk of a stage."""
    total, perturbed = int(settings["trajectories"]), int(settings["perturbed"])
    allocations = proportional_chunk_allocations(
        balanced_region_counts(total, settings["dimension"]), int(settings["chunk_size"])
    )
    modes = allocate_mode_chunks(
        {NORMAL_MODE: total - perturbed, DRIFT_MODE: perturbed},
        [sum(allocation.values()) for allocation in allocations],
    )
    return list(zip(allocations, modes))


def _task_regions(region_counts, region_order):
    """The start region of each task of a chunk; the task index decides the episode's seed.

    ``cycle`` deals the regions in turn and ``blocks`` lists them one after another.
    Both give the same counts; the choice pairs seeds with regions, and each preset
    keeps the order of the data it was tuned on.
    """
    regions = sorted(region_counts)
    if region_order == "blocks":
        return [region for region in regions for _ in range(int(region_counts[region]))]
    if region_order != "cycle":
        raise ValueError(f"Unknown region_order: {region_order!r}.")
    left = {region: int(region_counts[region]) for region in regions}
    tasks = []
    while any(left.values()):
        for region in regions:
            if left[region]:
                tasks.append(region)
                left[region] -= 1
    return tasks


def build_chunk_configs(settings, chunk_index, region_counts, *, validation=False, mode_counts=None):
    """Describe the expert episodes of one chunk."""
    expert, dimension = settings["expert"], int(settings["dimension"])
    total = int(sum(region_counts.values()))
    if total < 1:
        raise ValueError("A chunk must contain a trajectory.")
    seed = int(settings["seed"]) + (VALIDATION_SEED_OFFSET if validation else 0)
    mode_counts = {NORMAL_MODE: total} if validation or mode_counts is None else mode_counts
    modes = [mode for mode, count in mode_counts.items() for _ in range(int(count))]
    if len(modes) != total:
        raise ValueError("Perturbation mode counts must match the chunk size.")
    np.random.default_rng(int(settings["seed"]) + chunk_index).shuffle(modes)

    configs = []
    for task_index, region in enumerate(_task_regions(region_counts, expert["region_order"])):
        config = {
            "seed": (seed + chunk_index * 1_000_003 + task_index) % (2**32 - 1),
            # The fixed 2D expert draws the center from its own stream.
            "center_seed": (seed + chunk_index * int(settings["chunk_size"]) + task_index) % (2**32 - 1),
            "region": int(region),
            # The fixed 3D expert splits the box itself, into the same regions.
            "octant": int(region),
            "start_bounds": region_bounds(expert["start_bounds"], region),
            "n_boids": int(expert["n_boids"]),
            "perception": float(expert["perception"]),
            "crowding": float(expert["crowding"]),
            "init_scatter": float(expert["init_scatter"]),
            "goal_arrival_radius": float(expert["goal_arrival_radius"]),
            "expert_max_steps": int(expert["expert_max_steps"]),
            "perturbation": episode_perturbation(settings["drift"], modes[task_index], dimension),
        }
        if settings["task"] == "online_goals":
            config.update(
                n_waypoints=int(expert["waypoints_per_episode"]),
                goal_bounds=tuple(expert["goal_bounds"]),
                goal_min_distance=float(expert["goal_min_distance"]),
            )
        else:
            config.update(goal_exclusion_size=float(expert["goal_exclusion_size"]))
        configs.append(config)
    return configs


def _timed(generator, config):
    started = time.perf_counter()
    trajectory = generator(config)
    return trajectory, time.perf_counter() - started


def generate_chunk(settings, chunk_index, region_counts, *, validation=False, mode_counts=None):
    """Generate one chunk's compiled trajectories in shared RAM.

    Returns the trajectories, their sampled centers and one record per trajectory.
    """
    configs = build_chunk_configs(settings, chunk_index, region_counts,
                                  validation=validation, mode_counts=mode_counts)
    total = len(configs)
    available = max(1, (os.cpu_count() or 2) - 2)
    workers = max(1, min(int(settings["generation_workers"]) or available, total))
    fixed, online, warm_up = compiled_expert(settings["dimension"])
    generator = online if settings["task"] == "online_goals" else fixed

    split = "validation" if validation else "training"
    print(f">>> Generating {total} {split} trajectories as dynamic tasks on {workers} CPU workers...", flush=True)
    started = time.perf_counter()
    warmup_seconds = warm_up()
    with ThreadPoolExecutor(max_workers=workers) as executor:
        generated = list(executor.map(lambda config: _timed(generator, config), configs))
    trajectories = [item[0] for item in generated]
    centers = np.stack([item.sampled_center for item in trajectories]).astype(np.float32, copy=False)
    records = [
        {
            "seed": int(config["seed"]),
            "region": int(config["region"]),
            "steps": int(item[0].steps),
            "seconds": float(item[1]),
        }
        for config, item in zip(configs, generated)
    ]
    print(
        f">>> {split.capitalize()} trajectories ready in {time.perf_counter() - started:.1f}s "
        f"(Numba warm-up {warmup_seconds:.1f}s), held in memory.",
        flush=True,
    )
    return trajectories, centers, records
